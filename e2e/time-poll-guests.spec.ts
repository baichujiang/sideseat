import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import { assertLocalTestDatabase } from "./helpers/local-test-database";

assertLocalTestDatabase();
const prisma = new PrismaClient();
const pollTokens: string[] = [];
test.afterAll(async () => {
  await prisma.timePoll.deleteMany({ where: { token: { in: pollTokens } } });
  await prisma.$disconnect();
});

test("guests fill, rename and confirm in the browser while the app shares their names and calendar outcome", async ({ browser, request, baseURL }) => {
  test.setTimeout(180_000);
  const usersBefore = await prisma.user.count();
  const login = await request.post("/api/v1/auth/login", { data: { identifier: "test_001", password: "Password123", device: { id: randomUUID(), name: "Guest plan QA", appVersion: "1.0.0", platformVersion: "26.0" } } });
  expect(login.status()).toBe(200);
  const headers = { Authorization: `Bearer ${(await login.json()).data.tokens.accessToken}` };
  const date = new Date(Date.now() + 3 * 86400_000).toISOString().slice(0, 10);
  const created = await request.post("/api/v1/time-polls", { headers: { ...headers, "Idempotency-Key": randomUUID() }, data: { title: "Guest friends at the library", timeZone: "Europe/Berlin", dates: [date], startMinute: 540, endMinute: 720, durationMinutes: 60, expectedCount: 3 } });
  expect(created.status()).toBe(201);
  let poll = (await created.json()).data;
  const token = poll.token; pollTokens.push(token);
  const publicPath = `/api/public/time-polls/${token}`;
  const nativePath = `/api/v1/time-polls/${token}`;
  expect((await request.put(`${nativePath}/response`, { headers, data: { displayName: "Host", slotIds: [0, 1, 2, 3] } })).status()).toBe(200);
  const guests = await Promise.all([0, 1].map(() => browser.newContext({ baseURL, viewport: { width: 390, height: 844 } })));
  try {
    await guests[0].addCookies([{ name: "NEXT_LOCALE", value: "en", url: baseURL! }]);
    const pages = await Promise.all(guests.map((context) => context.newPage()));
    const ids: string[] = [];
    for (let n = 0; n < 2; n++) {
      const page = pages[n];
      await page.goto(`/time-polls/${token}`);
      await expect(page.getByRole("heading", { name: "Guest friends at the library" })).toBeVisible();
      await expect(page.getByLabel("本次计划中的昵称")).toBeVisible();
      await expect(page.getByRole("main")).toHaveAttribute("lang", "zh-CN");
      await page.getByRole("button", { name: "Switch to English", exact: true }).click();
      await page.reload();
      await expect(page.getByRole("main")).toHaveAttribute("lang", "en");
      if (n === 0) expect((await guests[0].cookies()).find((cookie) => cookie.name === "NEXT_LOCALE")?.value).toBe("en");
      await page.getByLabel("Your name in this plan").fill(`Guest ${n + 1}`);
      await page.getByRole("button", { name: "Start or continue", exact: true }).click();
      for (const id of [0, 2]) await page.getByTestId(`time-poll-cell-${id}`).click();
      await expect(page.getByRole("status")).toHaveText("Saved");
      if (n === 0) await page.screenshot({ path: "/tmp/sideseat-guest103/guest-availability.png", fullPage: true });
      ids.push((await (await guests[n].request.get(publicPath)).json()).data.viewerId);
    }
    const cookies = await guests[0].cookies();
    expect(cookies.find((cookie) => cookie.name === "sideseat_poll_participant")).toMatchObject({ httpOnly: true, sameSite: "Lax", path: publicPath });
    await pages[0].getByRole("button", { name: "Edit nickname" }).click();
    await pages[0].getByLabel("Your name in this plan").fill("小林 Lin");
    await pages[0].getByRole("button", { name: "Save name", exact: true }).click();
    await expect(pages[0].getByRole("button", { name: "Edit nickname" })).toBeVisible();
    await pages[0].reload();
    await expect(pages[0].getByRole("main")).toContainText("小林 Lin");
    expect((await guests[0].request.patch(`${publicPath}/participant`, { data: { participantId: ids[1], displayName: "Impersonation" } })).status()).toBe(401);
    expect((await request.put(`${publicPath}/response`, { data: { participantId: ids[0], displayName: "Impersonation", slotIds: [] } })).status()).toBe(401);
    expect((await guests[0].request.patch(`${publicPath}/participant`, { headers: { Origin: "https://unrelated.example" }, data: { participantId: ids[0], displayName: "Cross origin" } })).status()).toBe(403);
    expect((await request.get(nativePath)).status()).toBe(401);
    poll = (await (await request.get(nativePath, { headers })).json()).data;
    expect(poll.participants.filter((person: { isGuest: boolean }) => person.isGuest).map((person: { displayName: string }) => person.displayName).sort()).toEqual(["Guest 2", "小林 Lin"]);
    expect(poll.summary).toMatchObject({ maximum: 3, common: true });
    expect(await prisma.user.count()).toBe(usersBefore);
    const sent = await request.post(`${nativePath}/invitations`, { headers, data: { version: 0, start: poll.slots[0].start, attendeeIds: poll.participants.map((person: { id: string }) => person.id) } });
    expect(sent.status()).toBe(200);
    const where = { timePoll: { token } };
    expect(await prisma.calendarEntry.count({ where })).toBe(0);
    await pages[0].reload();
    await pages[0].getByRole("button", { name: "Edit nickname" }).click();
    await pages[0].getByLabel("Your name in this plan").fill("小林");
    await pages[0].getByRole("button", { name: "Save name", exact: true }).click();
    await pages[0].getByRole("button", { name: "Confirm participation", exact: true }).click();
    await expect(pages[0].getByRole("button", { name: "You've confirmed", exact: true })).toBeDisabled();
    expect(await prisma.calendarEntry.count({ where })).toBe(0);
    await pages[1].reload();
    await pages[1].getByRole("button", { name: "Confirm participation", exact: true }).click();
    await expect(pages[1].getByRole("heading", { name: "Plan confirmed", exact: true })).toBeVisible();
    const entries = await prisma.calendarEntry.findMany({ where, include: { companions: true } });
    expect(entries).toHaveLength(1);
    expect(entries[0].companions.map((person) => ({ userId: person.userId, displayName: person.displayName })).sort((a, b) => a.displayName.localeCompare(b.displayName))).toEqual([{ userId: null, displayName: "Guest 2" }, { userId: null, displayName: "小林" }]);
    const schedule = await request.get("/api/v1/home/schedule", { headers, params: { windowStart: `${date}T00:00:00.000Z`, windowEnd: `${date}T23:59:59.000Z` } });
    expect(schedule.status()).toBe(200);
    expect((await schedule.json()).data.studyEntries.find((entry: { timePollToken: string }) => entry.timePollToken === token).eventParticipants).toHaveLength(2);
    await pages[1].screenshot({ path: "/tmp/sideseat-guest103/guest-confirmed.png", fullPage: true });
    expect((await guests[0].request.patch(`${publicPath}/participant`, { data: { participantId: ids[0], displayName: "Late rename" } })).status()).toBe(409);
    expect((await request.post(`${nativePath}/cancel`, { headers, data: { version: 1 } })).status()).toBe(200);
    expect(await prisma.calendarEntry.count({ where })).toBe(0);
    const fixed = await request.post("/api/v1/time-polls", { headers: { ...headers, "Idempotency-Key": randomUUID() }, data: { title: "Direct-time guest plan", timeZone: "Europe/Berlin", dates: [date], startMinute: 540, endMinute: 720, durationMinutes: 60, expectedCount: 2, planningMode: "FIXED", fixedStart: `${date}T08:00:00.000Z` } });
    expect(fixed.status()).toBe(201);
    const fixedToken = (await fixed.json()).data.token; pollTokens.push(fixedToken);
    await pages[0].getByRole("button", { name: "切换为中文", exact: true }).click();
    await pages[0].goto(`/time-polls/${fixedToken}`);
    await expect(pages[0].getByRole("main")).toHaveAttribute("lang", "zh-CN");
    const directJoin = await guests[0].request.post(`/api/public/time-polls/${fixedToken}/participant`, { data: { displayName: "Lin" } });
    expect(directJoin.status()).toBe(200);
    const directId = (await directJoin.json()).data.viewerId;
    const reply = (status: string) => guests[0].request.put(`/api/public/time-polls/${fixedToken}/invitation-response`, { data: { participantId: directId, version: 1, status } });
    expect((await reply("DECLINED")).status()).toBe(200);
    expect(await prisma.calendarEntry.count({ where: { timePoll: { token: fixedToken } } })).toBe(0);
    expect((await reply("ACCEPTED")).status()).toBe(200);
    expect(await prisma.calendarEntry.count({ where: { timePoll: { token: fixedToken } } })).toBe(1);
    await pages[0].emulateMedia({ colorScheme: "dark" });
    await pages[0].reload();
    await expect(pages[0].getByRole("heading", { name: /Plan confirmed|计划已确定/ })).toBeVisible();
    await pages[0].screenshot({ path: "/tmp/sideseat-guest103/guest-direct-confirmed.png", fullPage: true });
  } finally { await Promise.all(guests.map((context) => context.close())); }
});
